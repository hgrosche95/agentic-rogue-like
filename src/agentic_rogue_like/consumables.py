"""Scripts: the run's consumables - one-shot programs the player carries.

Five fixed effects (CONSUMABLE_POOL), never generated by an agent and never
upgraded. Running one mid-fight costs no field slot and no context tokens: it
is the player's own turn, so it is free apart from the script itself.

Scripts come from a won fight or from a black market (shop.py). The drop roll
has its own rng, seeded from the run seed and the room like the artifact offers
there, so picking one up never shifts the run rng's sequence - a seeded run
stays seeded. The bag holds at most MAX_CONSUMABLES of them; add_consumable is
the single place that decides whether an offer fits.
"""

from __future__ import annotations

import random

from .artifacts import heal
from .combat import CombatState, _damage_enemy, _draw
from .models import (
    MAX_CONSUMABLES,
    Consumable,
    ConsumableKind,
    PlayerState,
    RunState,
    Status,
)

HEAL_AMOUNT = 10
BLOCK_AMOUNT = 8
DRAW_COUNT = 2
DAMAGE_AMOUNT = 10

# A won fight leaves a script behind this often.
DROP_CHANCE = 0.3
# What a black market charges for one, and how many it stocks (shop.py).
SCRIPT_BASE_PRICE = 30
SHOP_SCRIPTS = 2

CONSUMABLE_POOL: tuple[Consumable, ...] = (
    Consumable(
        kind=ConsumableKind.HEAL,
        name="patch.sh",
        description=f"Restore {HEAL_AMOUNT} integrity.",
    ),
    Consumable(
        kind=ConsumableKind.BLOCK,
        name="firewall.sh",
        description=f"Gain {BLOCK_AMOUNT} block.",
    ),
    Consumable(
        kind=ConsumableKind.DRAW,
        name="fetch.sh",
        description=f"Draw {DRAW_COUNT} cards.",
    ),
    Consumable(
        kind=ConsumableKind.DAMAGE,
        name="kill.sh",
        description=f"Deal {DAMAGE_AMOUNT} damage to the enemy.",
    ),
    Consumable(
        kind=ConsumableKind.PURGE,
        name="antivirus.sh",
        description="Remove every Malware stack you carry.",
    ),
)


def add_consumable(player: PlayerState, item: Consumable) -> bool:
    """Put `item` in the bag, or report that there is no room for it.

    The only place MAX_CONSUMABLES is enforced: at `len >= MAX_CONSUMABLES`
    nothing changes and the call returns False. A copy goes into the bag, so
    the offer it came from (a shop slot, the pool) stays untouched."""
    if len(player.consumables) >= MAX_CONSUMABLES:
        return False
    player.consumables.append(item.model_copy())
    return True


def roll_drop(run: RunState, node_id: str) -> Consumable | None:
    """The script a won fight leaves behind - None most of the time.

    Its own rng, seeded by the run seed, the act and the room, so the roll
    never touches the run rng's sequence and repeats exactly for a seed."""
    rng = random.Random(f"{run.seed}-script-{run.act}-{node_id}")
    if rng.random() >= DROP_CHANCE:
        return None
    return rng.choice(CONSUMABLE_POOL)


def use_consumable(
    state: CombatState, player: PlayerState, index: int, rng: random.Random
) -> str:
    """Run the bag's script `index` in the ongoing fight and return its log line.

    Raises ValueError if the fight is already decided (a win or a knockout -
    there is no turn left to spend it on) or the index is out of range. The
    script is gone either way once it resolves, including a purge that found no
    Malware; nothing is removed before the checks pass."""
    if state.enemy_hp <= 0:
        raise ValueError("the fight is already won")
    if player.hp <= 0:
        raise ValueError("you are already down")
    if not 0 <= index < len(player.consumables):
        raise ValueError(f"script index {index} is out of range")

    item = player.consumables[index]
    if item.kind is ConsumableKind.HEAL:
        line = f"You run {item.name}, restoring {heal(player, HEAL_AMOUNT)} integrity."
    elif item.kind is ConsumableKind.BLOCK:
        state.player_block += BLOCK_AMOUNT
        line = f"You run {item.name}, gaining {BLOCK_AMOUNT} block."
    elif item.kind is ConsumableKind.DRAW:
        line = f"You run {item.name}, drawing {_draw(state, DRAW_COUNT, rng)} card(s)."
    elif item.kind is ConsumableKind.DAMAGE:
        absorbed, dealt = _damage_enemy(state, DAMAGE_AMOUNT)
        block_note = f" - its block absorbs {absorbed}, {dealt} gets through" if absorbed else ""
        line = (
            f"You run {item.name}, dealing {DAMAGE_AMOUNT} damage{block_note}. "
            f"{state.enemy.name} at {state.enemy_hp} integrity."
        )
    else:  # PURGE
        stacks = state.player_status.pop(Status.MALWARE, 0)
        cleared = f"clearing {stacks} Malware stack(s)" if stacks else "finding no Malware on you"
        line = f"You run {item.name}, {cleared}."

    player.consumables.pop(index)
    return line
